export function homepageImageUrl(value = "", usage = "card") {
  const raw = String(value || "").trim();
  if (!raw) return "";
  try {
    const url = new URL(raw, "https://www.suiyuecare.com/");
    if (!["www.suiyuecare.com", "suiyuecare.com"].includes(url.hostname)) return raw;
    const variant = homepageImageVariants[url.pathname.replace(/^\//, "")]?.[usage];
    // Use root-relative paths so CMS values work after navigating from a detail page.
    return variant ? `/${variant}` : raw;
  } catch {
    return raw;
  }
}
