-- Visual page editor: page-level drafts, atomic Owner review, and canonical
-- template fields. Existing ungrouped publish requests remain supported.

create table if not exists public.cms_change_sets (
  id uuid primary key default gen_random_uuid(),
  page_slug text not null,
  scope_key text not null references public.cms_content_areas(scope_key) on update cascade on delete restrict,
  title text not null,
  status text not null default 'draft',
  draft_payload jsonb not null default '{"version":1,"changes":[]}'::jsonb,
  requested_by uuid not null references public.profiles(id) on delete restrict,
  department_id uuid not null references public.departments(id) on delete restrict,
  submitted_at timestamptz,
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  reviewer_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint cms_change_sets_page_slug_format check (page_slug ~ '^[a-z0-9][a-z0-9-]*$'),
  constraint cms_change_sets_status_check check (status in ('draft', 'pending', 'approved', 'rejected', 'cancelled')),
  constraint cms_change_sets_payload_shape check (
    jsonb_typeof(draft_payload) = 'object'
    and jsonb_typeof(draft_payload->'changes') = 'array'
  )
);

create unique index if not exists cms_change_sets_one_draft_per_page_idx
on public.cms_change_sets(requested_by, page_slug)
where status = 'draft';

create index if not exists cms_change_sets_scope_status_idx
on public.cms_change_sets(scope_key, status, updated_at desc);

create index if not exists cms_change_sets_requester_idx
on public.cms_change_sets(requested_by, updated_at desc);

drop trigger if exists set_cms_change_sets_updated_at on public.cms_change_sets;
create trigger set_cms_change_sets_updated_at
before update on public.cms_change_sets
for each row execute function public.set_updated_at();

alter table public.publish_requests
  add column if not exists change_set_id uuid references public.cms_change_sets(id) on delete set null;

create index if not exists publish_requests_change_set_idx
on public.publish_requests(change_set_id, status, requested_at desc);

